"""Execute production thermald target replacement and trip/controller selection.

The XML comes from this repository's PowerController.xml. ElementTree maps it
to the upstream parser's typed structures (a parser double). The existing-zone
positive-temperature sensor/binding branch, zone add_trip/update_trip_temp,
trip selection and RAPL controller are exact pinned upstream C++. Engine and
sensor discovery, non-RAPL cooling devices, sysfs, polling-trip maintenance,
PPCC, PID and process-exit restoration are doubles or excluded. time() is a
controlled clock double; original native debounce and controller functions run
unchanged against one-second observations, without sleeping or adjusting clocks. This does not
execute libxml parsing, complete engine startup, IRQs or physical cooling.
"""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import resource
import subprocess
import tempfile
import unittest
import xml.etree.ElementTree as ET

from test_thermald_ceiling_runtime import COMMON, PID, SYSFS, actual_functions

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / 'tests/fixtures/thermald_v2_5_13'
SPEC = importlib.util.spec_from_file_location('target_power', ROOT / 'scripts/mechrevo_power.py')
POWER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(POWER)


def actual_xml_branch(source):
    anchor = source.index('// Add from XML thermal zone')
    start = source.index('\t\t\t\t\tcthd_sensor *sensor = search_sensor(', anchor)
    end = source.index(' else {', source.index('zone->add_trip(trip_pt);', start))
    return source[start:end].encode()


def parser_double(root):
    """Map the tested subset of product XML to typed upstream parser inputs."""
    platform = root.find('Platform')
    if platform is None or platform.findtext('Preference') != 'ENERGY_CONSERVE':
        raise AssertionError('Product XML must select energy conservation')
    ranges = {c.findtext('Type'): c for c in platform.findall('./CoolingDevices/CoolingDevice')}
    rapl = ranges['rapl_controller']
    zone = platform.find('./ThermalZones/ThermalZone')
    if zone is None or zone.findtext('Type') != 'cpu':
        raise AssertionError('Product XML must update native CPU zone')
    trips = zone.findall('./TripPoints/TripPoint')
    if len(trips) != 1:
        raise AssertionError('This fixture covers one positive-temperature trip')
    trip = trips[0]
    bindings = trip.findall('CoolingDevice')
    tokens = [rapl.findtext('MinState'), rapl.findtext('MaxState'), trip.findtext('SensorType'),
              trip.findtext('Temperature'), trip.findtext('Hyst'), trip.findtext('type'),
              trip.findtext('ControlType'), str(len(bindings))]
    for binding in bindings:
        # Actual upstream defaults for fields not generated by product XML are
        # supplied in C++; influence and sampling are present and read here.
        tokens += [binding.findtext('type'), binding.findtext('influence'),
                   binding.findtext('SamplingPeriod')]
    if any(not isinstance(token, str) or not token or any(c.isspace() for c in token) for token in tokens):
        raise AssertionError('Missing or malformed product XML field')
    # Absent parameter retains constructor default, rather than synthesizing 0.
    debounce = rapl.findtext('DebouncePeriod')
    tokens.append('-1' if debounce is None else debounce)
    return ' '.join(tokens) + '\n'


class ThermaldTargetRuntime(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        for manifest_name in ('provenance.json', 'target_provenance.json'):
            manifest = json.loads((SNAPSHOT / manifest_name).read_text())
            for name, item in manifest['files'].items():
                raw = (SNAPSHOT / name).read_bytes()
                if hashlib.sha256(raw).hexdigest() != item['snapshot_sha256']:
                    raise AssertionError('Frozen snapshot hash changed: ' + name)
                for function, expected in item.get('functions', {}).items():
                    if hashlib.sha256(actual_functions(raw.decode(), function)).hexdigest() != expected:
                        raise AssertionError('Frozen function hash changed: ' + function)
                upstream = os.environ.get('THERMALD_PINNED_SOURCE_DIR')
                if upstream:
                    original = (Path(upstream) / item['upstream_path']).read_bytes()
                    if hashlib.sha256(original).hexdigest() != item['upstream_sha256']:
                        raise AssertionError('Upstream source hash changed: ' + name)
                    for function in item.get('functions', {}):
                        if actual_functions(original.decode(), function) != actual_functions(raw.decode(), function):
                            raise AssertionError('Snapshot differs from upstream: ' + function)
                    if 'block_sha256' in item:
                        block = actual_xml_branch(original.decode())
                        if hashlib.sha256(block).hexdigest() != item['block_sha256']:
                            raise AssertionError('XML branch differs from upstream')
                        # Snapshot contains the unmodified GPL license header
                        # followed immediately by this exact production slice.
                        if raw[raw.index(b'*/')+3:-1] != block:
                            raise AssertionError('XML snapshot body differs from original')
                    if 'native_order_sha256' in item:
                        text = original.decode()
                        start = text.index('const char * const def_cooling_devices[]')
                        end = text.index(';', start)+1
                        block = text[start:end].encode()
                        if (hashlib.sha256(block).hexdigest() != item['native_order_sha256']
                                or raw[raw.index(b'*/')+3:-1] != block):
                            raise AssertionError('Native default order differs from original')
        temporary_root = Path(os.environ.get('TMPDIR', ROOT / '.local-tests'))
        temporary_root.mkdir(parents=True, exist_ok=True)
        cls.temporary = tempfile.TemporaryDirectory(prefix='thermald-target-', dir=temporary_root)
        cls.addClassCleanup(cls.temporary.cleanup)
        path = Path(cls.temporary.name)
        headers = {'thd_common.h': COMMON, 'thd_sys_fs.h': SYSFS, 'thd_pid.h': PID,
                   'thd_adaptive_types.h': '#pragma once\nstruct adaptive_target { '
                                         'std::string code; std::string argument; };\n'}
        for name, content in headers.items():
            (path / name).write_text(content)
        source = (ROOT / 'tests/fixtures/thermald_target_runtime.cpp').read_text()
        for marker, name in (('/* @ACTUAL_CDEV@ */', 'thd_cdev.cpp'),
                             ('/* @ACTUAL_RAPL@ */', 'thd_cdev_rapl.cpp'),
                             ('/* @ACTUAL_TRIP@ */', 'thd_trip_point.cpp'),
                             ('/* @ACTUAL_ZONE@ */', 'target_thd_zone.cpp'),
                             ('/* @ACTUAL_NATIVE_ORDER@ */', 'target_native_order.cpp'),
                             ('/* @ACTUAL_XML_BRANCH@ */', 'target_xml_existing_zone.cpp')):
            if source.count(marker) != 1:
                raise AssertionError('Bad production insertion marker: ' + marker)
            source = source.replace(marker, (SNAPSHOT / name).read_text())
        compilation = path / 'actual-target.cpp'
        compilation.write_text(source)
        cls.binary = path / 'actual-target'
        compiled = subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O2', '-Wall', '-Wextra',
                                   '-Werror', '-Wno-unused-parameter', '-I'+str(path), '-I'+str(SNAPSHOT),
                                   str(compilation), '-o', str(cls.binary)], capture_output=True, text=True)
        if compiled.returncode:
            raise AssertionError(compiled.stdout + compiled.stderr)

    def xml(self):
        return ET.fromstring(POWER.PowerController.xml(55_000_000, 'ENERGY_CONSERVE', 90))

    def run_case(self, case='qualified', root=None, expected=0):
        def no_core():
            resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
        result = subprocess.run([str(self.binary), case], input=parser_double(root if root is not None else self.xml()),
                                capture_output=True, text=True, timeout=10, preexec_fn=no_core)
        self.assertEqual(result.returncode, expected, result.stdout + result.stderr)
        return result

    def test_generated_target90_xml_replaces_passive95_preserves_active_and_escalates_native_order(self):
        self.run_case()

    def test_one_second_platform_polling_preserves_native_trip_and_controller_behavior(self):
        root = ET.fromstring(POWER.PowerController.xml(55_000_000, 'ENERGY_CONSERVE', 90, 1))
        self.assertEqual(root.findtext('./Platform/PollingInterval'), '1')
        self.run_case(root=root)
        # This fixture executes trips/controllers, not the engine polling loop.
        # Removing only the platform interval must recover the legacy policy.
        platform = root.find('Platform')
        platform.remove(platform.find('PollingInterval'))
        self.assertEqual(ET.tostring(root), ET.tostring(self.xml()))

    def test_native_default_two_second_debounce_reacts_every_third_one_second_observation(self):
        result = self.run_case('debounce_default')
        self.assertIn('RAPL action seconds: 1000 1003 1006', result.stdout)

    def test_explicit_zero_debounce_reacts_each_second_without_changing_native_fallbacks(self):
        root = ET.fromstring(POWER.PowerController.xml(55_000_000, 'ENERGY_CONSERVE', 90, 1, 0))
        rapl = root.find('./Platform/CoolingDevices/CoolingDevice')
        self.assertEqual(rapl.findtext('Type'), 'rapl_controller')
        self.assertEqual(rapl.findtext('DebouncePeriod'), '0')
        result = self.run_case('debounce_zero', root)
        self.assertIn('RAPL action seconds: 1000 1001 1002', result.stdout)
        # Product policy changes only the MSR RAPL device's native debounce.
        rapl.remove(rapl.find('DebouncePeriod'))
        platform = root.find('Platform')
        platform.remove(platform.find('PollingInterval'))
        self.assertEqual(ET.canonicalize(ET.tostring(root), strip_text=True),
                         ET.canonicalize(ET.tostring(self.xml()), strip_text=True))

    def test_reverting_zero_debounce_to_native_default_fails_one_second_qualification(self):
        root = ET.fromstring(POWER.PowerController.xml(55_000_000, 'ENERGY_CONSERVE', 90, 1, 0))
        root.find('./Platform/CoolingDevices/CoolingDevice/DebouncePeriod').text = '2'
        result = self.run_case('debounce_zero', root, expected=1)
        self.assertIn('debounce did not select', result.stderr)

    def test_wrong_hysteresis_counterexamples_fail_native_qualification(self):
        for value in ('0', '2999', '3001'):
            with self.subTest(hysteresis=value):
                root = self.xml()
                root.find('./Platform/ThermalZones/ThermalZone/TripPoints/TripPoint/Hyst').text = value
                self.run_case(root=root, expected=1)

    def test_old95_counterexample_fails_the_same_runtime_qualification(self):
        root = self.xml()
        root.find('./Platform/ThermalZones/ThermalZone/TripPoints/TripPoint/Temperature').text = '95000'
        result = self.run_case(root=root, expected=1)
        self.assertIn('qualification failed', result.stderr)

    def test_dropped_or_reordered_native_binding_counterexamples_fail(self):
        for mode in ('drop', 'reorder', 'influence', 'sampling'):
            with self.subTest(mode=mode):
                root = self.xml()
                trip = root.find('./Platform/ThermalZones/ThermalZone/TripPoints/TripPoint')
                bindings = trip.findall('CoolingDevice')
                if mode == 'drop': trip.remove(bindings[-1])
                elif mode == 'reorder':
                    trip.remove(bindings[0]); trip.append(bindings[0])
                elif mode == 'influence': bindings[-1].find('influence').text = '1'
                else: bindings[-1].find('SamplingPeriod').text = '1'
                self.run_case(root=root, expected=1)

    def test_unavailable_cdev_is_skipped_by_production_but_not_falsely_qualified(self):
        self.run_case('missing_cdev')

    def test_invalid_sensor_production_fallback_retains_binding_but_cannot_qualify(self):
        root = self.xml()
        root.find('./Platform/ThermalZones/ThermalZone/TripPoints/TripPoint/SensorType').text = 'missing_sensor'
        self.run_case('invalid_sensor', root)

    def test_zero_temperature_is_explicitly_outside_positive_trip_replacement(self):
        root = self.xml()
        root.find('./Platform/ThermalZones/ThermalZone/TripPoints/TripPoint/Temperature').text = '0'
        self.run_case('zero_temperature', root)

    def test_parser_double_rejects_missing_fields_instead_of_supplying_zero(self):
        root = self.xml()
        trip = root.find('./Platform/ThermalZones/ThermalZone/TripPoints/TripPoint')
        trip.remove(trip.find('SensorType'))
        with self.assertRaisesRegex(AssertionError, 'Missing or malformed'):
            parser_double(root)


if __name__ == '__main__':
    unittest.main()
